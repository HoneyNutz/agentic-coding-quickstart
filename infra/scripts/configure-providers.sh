#!/usr/bin/env bash
# Run ON THE HOST (as an admin, via PIM-activated "Virtual Machine Administrator
# Login") after the first deployment. Writes one root-owned provider file per
# agent and stores each agent's Foundry API key in acq's secret store.
#
#   sudo ./configure-providers.sh OPENCODE_SUBDOMAIN CODEX_SUBDOMAIN CLAUDE_SUBDOMAIN [ACR_LOGIN_SERVER]
#
# Subdomains come from the deployment output `foundryEndpoints`. Keys are read
# from the terminal (never argv, never shell history) and piped straight into
# `acq secret set`; they are never written to the provider files.
set -euo pipefail

[ "$(id -u)" -eq 0 ] || { echo "run with sudo" >&2; exit 1; }
[ "$#" -ge 3 ] || { sed -n '2,11p' "$0" >&2; exit 1; }

opencode_sub=$1 codex_sub=$2 claude_sub=$3 acr=${4:-}
for s in "$opencode_sub" "$codex_sub" "$claude_sub"; do
  [[ "$s" =~ ^[a-z0-9][a-z0-9-]{1,62}$ ]] || { echo "bad subdomain: $s" >&2; exit 1; }
done

# Digests are pinned by scripts/mirror-images.sh; edit these after mirroring.
image_line() {
  local agent=$1 digest_file=/etc/ai-sandbox/images/$1.digest
  if [ -n "$acr" ] && [ -f "$digest_file" ]; then
    printf 'ACQ_AGENT_IMAGE=%s/sandbox-templates/%s@%s\n' "$acr" "$agent" "$(cat "$digest_file")"
  fi
}

write_provider() {
  local agent=$1 host=$2 base_url=$3 key_env=$4 model=$5
  local f=/etc/ai-sandbox/providers/$agent.env
  {
    echo "# Generated by configure-providers.sh. Root-owned; read by sandbox-run."
    echo "ACQ_PROVIDER=azure-$agent"
    echo "ACQ_PROVIDER_NAME=Azure Foundry ($agent)"
    echo "ACQ_PROVIDER_HOST=$host"
    echo "ACQ_PROVIDER_BASE_URL=$base_url"
    echo "ACQ_PROVIDER_KEY_ENV=$key_env"
    echo "ACQ_PROVIDER_MODEL=$model"
    image_line "$agent"
  } > "$f"
  chown root:root "$f"
  chmod 0644 "$f"
  echo "wrote $f"
}

# opencode and codex speak the OpenAI-compatible Azure OpenAI v1 API.
write_provider opencode "$opencode_sub.openai.azure.com" \
  "https://$opencode_sub.openai.azure.com/openai/v1" AZURE_OPENAI_API_KEY gpt-opencode
write_provider codex "$codex_sub.openai.azure.com" \
  "https://$codex_sub.openai.azure.com/openai/v1" AZURE_OPENAI_API_KEY gpt-codex
# claude speaks the Anthropic Messages API exposed by Foundry.
write_provider claude "$claude_sub.services.ai.azure.com" \
  "https://$claude_sub.services.ai.azure.com/anthropic" ANTHROPIC_API_KEY claude-sonnet

for agent in opencode codex claude; do
  printf 'Paste the API key for the %s Foundry account (input hidden): ' "$agent"
  IFS= read -rs key
  echo
  [ -n "$key" ] || { echo "empty key; skipping $agent" >&2; continue; }
  # shellcheck disable=SC2016
  # NO_LIVE_REFEED: a global set would otherwise bind this key into every
  # existing sandbox, including other agents' sandboxes.
  printf '%s\n' "$key" | sudo -u ai-sandbox -H env HOME=/var/lib/ai-sandbox/home ACQ_SECRET_NO_LIVE_REFEED=1 \
    PATH=/var/lib/ai-sandbox/home/.local/bin:/usr/bin:/bin \
    bash -c 'set -a; . "/etc/ai-sandbox/providers/$1.env"; set +a; acq secret set -g "$ACQ_PROVIDER" --host "$ACQ_PROVIDER_HOST" --env "$ACQ_PROVIDER_KEY_ENV"' _ "$agent"
  unset key
  echo "stored key for azure-$agent"
done
